#!/usr/bin/env python3
"""Embeds files in a C source as one string constant per file, plus a table.

Used by the Makefile to embed the Z runtime and the Z standard library in the
compiler, so a built `z` needs nothing else on disk to compile a program.

Each file becomes its own `static const char <prefix>_<n>[]`, and the tables
`<prefix>_names` and `<prefix>_srcs` pair them up, so the driver can lex each
file separately and stamp the right name on its tokens. Bytes outside printable
ASCII are emitted as three-digit octal escapes: the sources are arbitrary bytes
and must not be able to end the literal early, and octal has no ambiguity about
how many digits it takes the way \\x does.

A literal is wrapped into adjacent string fragments so no line runs past
WIDTH. C concatenates them, so the bytes are the same either way, and a
28KB standard library on one line is a line no `git diff` can show a change
on. The header is generated, so it is the one file in the tree whose diffs
have to be readable, and it is only readable if it is wrapped.
"""
import sys

# Longest output line, indent and quotes included.
WIDTH = 100


def c_bytes(data: bytes) -> list:
    """Escapes `data` into a list of C string-literal pieces.

    Each piece is one printable character or one complete escape sequence, so a
    caller that has to cut the literal somewhere can cut between the pieces
    without ever splitting an escape in half.

    Bytes outside printable ASCII are emitted as three-digit octal escapes: the
    sources are arbitrary bytes and must not be able to end the literal early,
    and octal has no ambiguity about how many digits it takes the way \\x does.
    """
    out = []
    for b in data:
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return out


def fragments(pieces: list, width: int) -> list:
    """Splits an escaped literal into chunks that each fit on one line.

    Breaks after the last space that fits, so a line ends at a word rather than
    mid-word. A run with no space in it -- a long identifier, a comment with its
    newlines escaped -- is cut at the width instead, which is the only thing that
    can be done to it.

    An escape sequence is never split, because the input is a list of pieces
    and a piece is never divided. Cutting the escaped text by character
    position instead could land between the two characters of an escaped
    backslash, and a string literal cannot end in a lone backslash: the C
    compiler reads it as the start of an escape and runs on into the next line
    looking for the character it names, so the generated header does not
    compile.
    """
    budget = width - len("    ") - 2  # indent, and the quotes on each side
    if budget < 1:
        raise ValueError("width %d is too narrow to hold any content" % width)
    out = []
    chunk = []
    used = 0
    for piece in pieces:
        if used + len(piece) > budget and chunk:
            # A space is a good place to break, so a line ends at a word.
            cut = None
            for i, p in enumerate(chunk):
                if p == " ":
                    cut = i + 1
            if cut is not None and cut < len(chunk):
                out.append("".join(chunk[:cut]))
                chunk = chunk[cut:]
                used = sum(len(p) for p in chunk)
            else:
                out.append("".join(chunk))
                chunk = []
                used = 0
        chunk.append(piece)
        used += len(piece)
    if chunk:
        out.append("".join(chunk))
    return out


def table_lines(items):
    """One entry per line, inside a `clang-format off` guard: the only layout
    that stays under the column limit for any number of files. clang-format
    would otherwise repack short tables onto shared lines, so its exact
    spacing would have to be replicated here to stay clean."""
    return ["    %s," % it for it in items]


def main() -> int:
    prefix, paths = sys.argv[1], sys.argv[2:]
    if not paths:
        print("usage: embed.py <prefix> <file>...", file=sys.stderr)
        return 2
    print("/* generated by tools/embed.py -- do not edit */")
    for i, p in enumerate(paths):
        with open(p, "rb") as f:
            pieces = c_bytes(f.read())
        if not pieces:
            # Nothing to wrap, and an empty pair of fragments would be two lines
            # saying nothing.
            print('static const char %s_%d[] = "";' % (prefix, i))
            continue
        chunks = fragments(pieces, WIDTH)
        print("static const char %s_%d[] =" % (prefix, i))
        for n, chunk in enumerate(chunks):
            tail = ";" if n == len(chunks) - 1 else ""
            print('    "%s"%s' % (chunk, tail))
    print("// clang-format off: table layout is fixed by the generator, not the formatter")
    print("static const char *const %s_names[] = {" % prefix)
    # The path is escaped for the same reason the source is: a name is data, and
    # one containing a quote would otherwise end the string early.
    for line in table_lines(['"%s"' % "".join(c_bytes(p.encode())) for p in paths]):
        print(line.rstrip())
    print("};")
    print("static const char *const %s_srcs[] = {" % prefix)
    for line in table_lines(["%s_%d" % (prefix, i) for i in range(len(paths))]):
        print(line.rstrip())
    print("};")
    print("// clang-format on")
    print("#define %s_COUNT %d" % (prefix, len(paths)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
